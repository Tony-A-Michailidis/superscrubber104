"""The rule reference: every check superscrubber104 can record, from the catalogue itself.

``superscrubber104 rules`` prints it and ``docs/rules.md`` is its Markdown output, kept in step by
a test, so the reference cannot drift from what the code checks. An assessor can read from it what
each finding means, which controls it is evidence for, and whether anyone can override it.
"""

