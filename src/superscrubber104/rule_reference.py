def _default(rule: RuleSpec) -> str:
    """What happens to a failing finding of this rule under the built-in defaults."""
    return "refuse (final)" if rule.final else DEFAULTS.severity[rule.severity].value


def rules_data() -> list[JSON]:
    return [
        {
            "id": rule.id,
            "version": rule.version,
            "title": rule.title,
            "severity": rule.severity.value,
            "final": rule.final,
            "default": _default(rule),
            "controls": list(rule.controls),
            "rationale": rule.rationale,
            "remediation": rule.remediation or None,
        }
        for rule in sorted(ALL, key=lambda r: r.id)
    ]


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def rules_markdown() -> str:
    final = sum(1 for rule in ALL if rule.final)
    lines = [
        "# Rule reference",
        "",
        "> Generated by `superscrubber104 rules --format md` from the rule catalogue. Do not edit "
        "by hand:",
        "> a test compares this file with the catalogue.",
        "",
        f"superscrubber104 records {len(ALL)} rules. Each finding names its rule, so this is what "
        "every line of a report means.",
        "",
        "* **Severity** is the rule's own. **Default** is what a failing finding leads to under "
        "the built-in policy defaults: `block`, `require-approval`, `warn` or `allow`. A policy "
        "can change both, per rule and per path.",
        f"* **refuse (final)** marks the {final} integrity and authenticity rules. No policy, "
        "waiver or approval can change them: if they could be overridden, the airlock would not "
        "be a control.",
        "* **Controls** are NIST SP 800-53 Rev 5 identifiers the finding is evidence for. A "
        "site can remap them (`controls.overrides`). superscrubber104 never marks a control "
        "satisfied: "
        "that is the assessor's call.",
        "* A check that could not run is recorded under the same rule as *not assessed*, never "
        "left out.",
        "",
    ]
    domains: dict[str, list[RuleSpec]] = {}
    for rule in sorted(ALL, key=lambda r: r.id):
        domains.setdefault(rule.id.split(".", 1)[0], []).append(rule)
    for domain, rules in sorted(domains.items(), key=lambda item: _DOMAINS.get(item[0], item[0])):
        lines += [
            f"## {_DOMAINS.get(domain, domain)}",
            "",
            "| Rule | Severity | Default | Controls | What it means |",
            "|---|---|---|---|---|",
        ]
        for rule in rules:
            meaning = f"**{_cell(rule.title)}.** {_cell(rule.rationale)}"
            if rule.remediation:
                meaning += f" *{_cell(rule.remediation)}*"
            lines.append(
                f"| `{rule.id}` | {rule.severity.value} | {_default(rule)} "
                f"| {', '.join(rule.controls)} | {meaning} |"
            )
        lines.append("")
    return "\n".join(lines)
